<script>
(function() {
    var header = document.querySelector('.c-header');
    var isHome = window.location.pathname === '/' || window.location.pathname === '/index' || window.location.pathname === '/index.php';
    var hasHash = window.location.hash && window.location.hash.length > 1;
    var isScrolled = !isHome || hasHash;

    // On homepage, swap links that have data-home-href to use the scroll version
    if (isHome) {
        document.querySelectorAll('a[data-home-href]').forEach(function(link) {
            link.setAttribute('href', link.getAttribute('data-home-href'));
        });
    }

    var fullHeight = 0;
    var scrolledHeight = 0;

    function measureHeights() {
        // Disable transitions during measurement so offsetHeight is accurate
        header.style.transition = 'none';
        var allTransitioned = header.querySelectorAll('*');
        allTransitioned.forEach(function(el) { el.style.transition = 'none'; });

        header.classList.remove('scrolled');
        header.offsetHeight; // force reflow
        fullHeight = header.offsetHeight;

        header.classList.add('scrolled');
        header.offsetHeight; // force reflow
        scrolledHeight = header.offsetHeight;

        if (isHome && !hasHash) {
            header.classList.remove('scrolled');
        }

        // Re-enable transitions
        header.style.transition = '';
        allTransitioned.forEach(function(el) { el.style.transition = ''; });
    }

    function updateBodyPadding() {
        document.body.style.paddingTop = (isScrolled ? scrolledHeight : fullHeight) + 'px';
    }

    window.addEventListener('load', function() {
        // If already scrolled down on load, treat as scrolled
        if (!isScrolled && window.scrollY > 80) {
            isScrolled = true;
        }
        if (isScrolled) {
            header.classList.add('scrolled');
        }
        measureHeights();
        updateBodyPadding();
        document.body.classList.remove('loading');
        var loader = document.getElementById('page-loader');
        loader.style.opacity = '0';
        setTimeout(function() { loader.style.display = 'none'; }, 300);

        // Handle hash scroll on page load
        if (window.location.hash) {
            setTimeout(function() {
                var target = document.querySelector(window.location.hash);
                if (target) {
                    header.classList.add('scrolled');
                    isScrolled = true;
                    updateBodyPadding();
                    // Wait for padding change to settle before measuring position
                    requestAnimationFrame(function() {
                        var top = target.offsetTop - scrolledHeight;
                        window.scrollTo({ top: top, behavior: 'smooth' });
                    });
                }
            }, 400);
        }
    });

    window.addEventListener('resize', function() {
        measureHeights();
        updateBodyPadding();
    });

    window.addEventListener('scroll', function() {
        if (!isScrolled && window.scrollY > 80) {
            header.classList.add('scrolled');
            isScrolled = true;
            updateBodyPadding();
        } else if (isHome && isScrolled && window.scrollY < 10) {
            header.classList.remove('scrolled');
            isScrolled = false;
            updateBodyPadding();
        }
    });

    // Smooth scroll for anchor links
    document.addEventListener('click', function(e) {
        var link = e.target.closest('a[href*="#"]');
        if (!link) return;
        var href = link.getAttribute('href');
        var hashIndex = href.indexOf('#');
        if (hashIndex === -1) return;
        var hash = href.substring(hashIndex);
        var path = href.substring(0, hashIndex);
        if (hash === '#' || hash === '') return;

        // If link is to current page or /index, scroll directly
        var currentPath = window.location.pathname.replace(/\/$/, '');
        var targetPath = path.replace(/\/$/, '');
        if (!targetPath || targetPath === currentPath || targetPath === '/index' && (currentPath === '/' || currentPath === '/index')) {
            var target = document.querySelector(hash);
            if (target) {
                e.preventDefault();
                var offset = scrolledHeight + 10;
                var top = target.getBoundingClientRect().top + window.pageYOffset - offset;
                window.scrollTo({ top: top, behavior: 'smooth' });
                history.pushState(null, '', hash);
            }
        }
    });
})();
</script>
